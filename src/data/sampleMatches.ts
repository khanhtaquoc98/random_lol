const ROLE_ORDER: Record<RoleId, number> = {
  TOP: 0,
  JG: 1,
  MID: 2,
  AD: 3,
  SP: 4,
};

export function mapRiotPositionToRole(
  teamPosition?: string,
  individualPosition?: string,
  indexInTeam = 0
): RoleId {
  const pos = (teamPosition || individualPosition || "").toUpperCase();
  if (pos === "TOP") return "TOP";
  if (pos === "JUNGLE") return "JG";
  if (pos === "MIDDLE" || pos === "MID") return "MID";
  if (pos === "BOTTOM" || pos === "BOT") return "AD";
  if (pos === "UTILITY" || pos === "SUPPORT") return "SP";
  const fallback: RoleId[] = ["TOP", "JG", "MID", "AD", "SP"];
  return fallback[indexInTeam % 5];
}

export function calculateMvpScore(
  p: {
    kills: number;
    deaths: number;
    assists: number;
    csPerMin: number;
    visionScore: number;
    win: boolean;
  },
  killParticipation: number,
  damageShare: number
): number {
  const kdaRatio = (p.kills + p.assists) / Math.max(1, p.deaths);
  const raw =
    kdaRatio * 12 +
    killParticipation * 0.45 +
    damageShare * 0.65 +
    p.csPerMin * 2.2 +
    p.visionScore * 0.35 +
    (p.win ? 8 : 0);
  return Math.min(99.9, Math.max(30, Number((raw / 1.15).toFixed(1))));
}

/**
 * Normalizes a raw Riot Match-V5 response object into NormalizedMatchData
 */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export function normalizeRiotMatchV5(rawMatch: any, platformOverride?: RiotPlatformId): NormalizedMatchData {
  const info = rawMatch?.info || {};
  const metadata = rawMatch?.metadata || {};
  const matchId: string = metadata.matchId || info.gameId?.toString() || "UNKNOWN_MATCH";
  const platformId = (platformOverride ||
    info.platformId ||
    matchId.split("_")[0] ||
    "VN2") as RiotPlatformId;

  const durationSec = Math.max(1, Number(info.gameDuration || 1800));
  const durationMin = durationSec / 60;

  const rawParticipants = Array.isArray(info.participants) ? info.participants : [];
  const rawTeams = Array.isArray(info.teams) ? info.teams : [];

  const buildTeam = (teamId: 100 | 200): TeamSummary => {
    const teamParticipants = rawParticipants.filter(
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      (p: any) => Number(p.teamId) === teamId
    );
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const teamMeta = rawTeams.find((t: any) => Number(t.teamId) === teamId) || {};
    const objs = teamMeta.objectives || {};

    const totalKills = teamParticipants.reduce(
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      (acc: number, p: any) => acc + Number(p.kills || 0),
      0
    );
    const totalGold = teamParticipants.reduce(
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      (acc: number, p: any) => acc + Number(p.goldEarned || 0),
      0
    );
    const totalDamage = teamParticipants.reduce(
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      (acc: number, p: any) => acc + Number(p.totalDamageDealtToChampions || 0),
      0
    );

    const SPELL_MAP: Record<number, string> = {
      1: "Thanh Tẩy",
      3: "Kiệt Sức",
      4: "Tốc Biến",
      6: "Tốc Hành",
      7: "Hồi Máu",
      11: "Trừng Phạt",
      12: "Dịch Chuyển",
      13: "Minh Mẫn",
      14: "Thiêu Đốt",
      21: "Lá Chắn",
      32: "Đánh Dấu (Cầu Tuyết)",
      39: "Đánh Dấu (Cầu Tuyết)",
    };

    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const participants: ParticipantStats[] = teamParticipants.map((p: any, idx: number) => {
      const kills = Number(p.kills || 0);
      const deaths = Number(p.deaths || 0);
      const assists = Number(p.assists || 0);
      const kda = Number(((kills + assists) / Math.max(1, deaths)).toFixed(2));
      const dmg = Number(p.totalDamageDealtToChampions || 0);
      const cs =
        Number(p.totalMinionsKilled || 0) + Number(p.neutralMinionsKilled || 0);
      const csPerMin = Number((cs / durationMin).toFixed(1));
      const kp =
        totalKills > 0
          ? Number((((kills + assists) / totalKills) * 100).toFixed(1))
          : 0;
      const dmgShare =
        totalDamage > 0 ? Number(((dmg / totalDamage) * 100).toFixed(1)) : 0;
      const role = mapRiotPositionToRole(
        p.teamPosition,
        p.individualPosition,
        idx
      );
      const win = Boolean(p.win);
      const visionScore = Number(p.visionScore || 0);

      return {
        puuid: p.puuid || `puuid-${teamId}-${idx}`,
        riotIdGameName:
          p.riotIdGameName || p.summonerName || `Player ${idx + 1}`,
        riotIdTagline: p.riotIdTagline || platformId,
        championId: p.championName || "Aatrox",
        championName: p.championName || "Aatrox",
        champLevel: Number(p.champLevel || 18),
        teamId,
        role,
        win,
        kills,
        deaths,
        assists,
        kda,
        largestKillingSpree: Number(p.largestKillingSpree ?? Math.max(0, kills - 1)),
        largestMultiKill: Number(p.largestMultiKill ?? (kills >= 4 ? 2 : 1)),
        visionWardsBoughtInGame: Number(p.visionWardsBoughtInGame ?? 0),
        damageDealtToTurrets: Number(p.damageDealtToTurrets ?? 0),
        totalDamageDealtToChampions: dmg,
        totalDamageTaken: Number(p.totalDamageTaken || 0),
        goldEarned: Number(p.goldEarned || 0),
        cs,
        csPerMin,
        visionScore,
        wardsPlaced: Number(p.wardsPlaced || 0),
        wardsKilled: Number(p.wardsKilled || 0),
        items: [
          Number(p.item0 || 0),
          Number(p.item1 || 0),
          Number(p.item2 || 0),
          Number(p.item3 || 0),
          Number(p.item4 || 0),
          Number(p.item5 || 0),
          Number(p.item6 || 0),
        ],
        summonerSpells: [
          SPELL_MAP[Number(p.summoner1Id)] || "Tốc Biến",
          SPELL_MAP[Number(p.summoner2Id)] || "Dịch Chuyển",
        ],
        primaryRune: "Chinh Phục",
        killParticipation: kp,
        damageShare: dmgShare,
        mvpScore: calculateMvpScore(
          { kills, deaths, assists, csPerMin, visionScore, win },
          kp,
          dmgShare
        ),
      };
    });

    participants.sort((a, b) => ROLE_ORDER[a.role] - ROLE_ORDER[b.role]);

    return {
      teamId,
      win: Boolean(teamMeta.win ?? participants[0]?.win),
      totalKills,
      totalGold,
      totalDamage,
      objectives: {
        baron: Number(objs.baron?.kills || 0),
        dragon: Number(objs.dragon?.kills || 0),
        horde: Number(objs.horde?.kills || 0),
        riftHerald: Number(objs.riftHerald?.kills || 0),
        tower: Number(objs.tower?.kills || 0),
        inhibitor: Number(objs.inhibitor?.kills || 0),
      },
      participants,
    };
  };

  const QUEUE_MAP: Record<number, string> = {
    420: "Xếp Hạng Đơn/Đôi (Ranked Solo/Duo)",
    440: "Xếp Hạng Linh Hoạt (Ranked Flex)",
    400: "Đánh Thường Cấm Chọn",
    430: "Đánh Thường Chọn Ẩn",
    490: "Đánh Nhanh (Quickplay)",
    450: "ARAM - Vực Gió Hú",
    100: "ARAM - Cầu Đồ Tể",
    2400: "ARAM - Cây Cầu Tiến Bộ",
    900: "ARURF",
    1900: "URF Chọn Tướng",
    1700: "Võ Đài (Arena)",
  };

  const rawGameMode = (info.gameMode || "CLASSIC").toUpperCase();
  const isAramMode =
    rawGameMode === "ARAM" ||
    [450, 100, 2400].includes(Number(info.queueId));

  return {
    matchId,
    platformId,
    gameMode: isAramMode ? "ARAM" : rawGameMode,
    queueName:
      QUEUE_MAP[Number(info.queueId)] ||
      (isAramMode
        ? "ARAM - Vực Gió Hú"
        : "Xếp Hạng Đơn/Đôi (Ranked Solo/Duo)"),
    gameDurationSeconds: durationSec,
    gameStartTimestamp: Number(info.gameStartTimestamp || Date.now() - 3600_000),
    gameVersion: info.gameVersion || "16.21.1",
    blueTeam: buildTeam(100),
    redTeam: buildTeam(200),
    source: "RIOT_API",
  };
}

